#!/usr/bin/env node
// Splits base-ib-playbook.html into portal modules and guides.
//
//   node scripts/import-playbook.mjs [path/to/base-ib-playbook.html]
//
// Writes:
//   src/content/playbook.generated.ts   module + guide HTML and metadata
//   public/playbook/*                   screenshots pulled out of the HTML
//
// Re-run it whenever the playbook HTML changes. Module slugs come from the
// titles, so renaming a module resets partners' progress for that module.

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(process.argv[2] ?? join(root, "..", "base-ib-playbook.html"));
const html = readFileSync(source, "utf8");

const GUIDE_IDS = { quickref: "Reference", glossary: "Reference", faq: "Support" };

const decode = (s) =>
  s
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&rsquo;|&lsquo;/g, "'")
    .replace(/&ldquo;|&rdquo;/g, '"')
    .replace(/&mdash;/g, "—")
    .replace(/&ndash;/g, "–");
const text = (s) => decode(s.replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim();
const slugify = (s) =>
  s.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const minutes = (s) => Math.max(1, Math.round(text(s).split(" ").length / 220));

function section(id) {
  const m = html.match(new RegExp(`<section[^>]*\\bid="${id}"[^>]*>([\\s\\S]*?)</section>`));
  if (!m) throw new Error(`Section #${id} not found in ${source}`);
  return m[1];
}

// Pull inline data: images out into public/playbook so pages stay light.
const imgDir = join(root, "public", "playbook");
rmSync(imgDir, { recursive: true, force: true });
mkdirSync(imgDir, { recursive: true });
let imgCount = 0;
function extractImages(fragment, slug) {
  return fragment.replace(/src="data:image\/(png|jpe?g|webp|gif);base64,([^"]+)"/g, (_, ext, b64) => {
    const file = `${slug}-${++imgCount}.${ext === "jpeg" ? "jpg" : ext}`;
    writeFileSync(join(imgDir, file), Buffer.from(b64, "base64"));
    return `src="/playbook/${file}" loading="lazy"`;
  });
}

function clean(fragment, slug) {
  let out = fragment
    .replace(/<div class="m-head">[\s\S]*?<\/div>\s*<\/div>/, "") // number + title: rendered by the page
    .replace(/<div class="complete-row">[\s\S]*?<\/div>/, "") // replaced by the portal's own button
    .replace(/\s+class="reveal"/g, "")
    .trim();
  return extractImages(out, slug);
}

function head(fragment) {
  const kicker = fragment.match(/<span class="kicker">([\s\S]*?)<\/span>/);
  const title = fragment.match(/<h2>([\s\S]*?)<\/h2>/);
  return { kicker: kicker ? text(kicker[1]) : "", title: title ? text(title[1]) : "" };
}

// Intro (hero)
const hero = section("start");
const intro = {
  title: text(hero.match(/<h2>([\s\S]*?)<\/h2>/)[1]),
  lede: text(hero.match(/<p class="lede">([\s\S]*?)<\/p>/)[1]),
  html: extractImages(
    hero
      .replace(/<span class="eyebrow">[\s\S]*?<\/span>/, "")
      .replace(/<h2>[\s\S]*?<\/h2>/, "")
      .replace(/<p class="lede">[\s\S]*?<\/p>/, "")
      .replace(/<div class="stat-row">[\s\S]*?<\/div>\s*<\/div>\s*<\/div>/, "")
      .trim(),
    "intro",
  ),
};

// Modules m1..mN in order
const modules = [];
for (let n = 1; ; n++) {
  if (!html.includes(`id="m${n}"`)) break;
  const raw = section(`m${n}`);
  const { kicker, title } = head(raw);
  const slug = slugify(title);
  modules.push({ slug, number: n, kicker, title, minutes: minutes(raw), html: clean(raw, slug) });
}

const guides = Object.entries(GUIDE_IDS).map(([id, fallbackKicker]) => {
  const raw = section(id);
  const { kicker, title } = head(raw);
  const slug = slugify(title);
  return { slug, kicker: kicker || fallbackKicker, title, minutes: minutes(raw), html: clean(raw, slug) };
});

const out = `// GENERATED by scripts/import-playbook.mjs — do not edit by hand.
// Source: base-ib-playbook.html

export const intro = ${JSON.stringify(intro, null, 2)} as const;

export const modules = ${JSON.stringify(modules, null, 2)} as const;

export const guides = ${JSON.stringify(guides, null, 2)} as const;
`;
mkdirSync(join(root, "src", "content"), { recursive: true });
writeFileSync(join(root, "src", "content", "playbook.generated.ts"), out);

console.log(`Imported ${modules.length} modules, ${guides.length} guides, ${imgCount} images.`);
for (const m of modules) console.log(`  ${String(m.number).padStart(2, "0")} ${m.title} (${m.minutes} min) → ${m.slug}`);
for (const g of guides) console.log(`  guide: ${g.title} → ${g.slug}`);
